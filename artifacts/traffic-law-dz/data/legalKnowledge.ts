export function searchLegalKnowledge(query: string): LegalQA[] {
  const q = query.trim().toLowerCase();
  if (!q || q.length < 2) return [];

  const words = q
    .split(/\s+/)
    .filter((w) => w.length >= 2)
    .map((w) => normalizeArabic(w));

  const scores: Array<{ qa: LegalQA; score: number }> = LEGAL_QA.map((qa) => {
    let score = 0;
    const qText = normalizeArabic(qa.question.toLowerCase());
    const aText = normalizeArabic(qa.answer.toLowerCase());
    const kText = qa.keywords.map((k) => normalizeArabic(k.toLowerCase())).join(" ");
    const tText = qa.tags.join(" ");

    for (const word of words) {
      if (word.length < 2) continue;
      if (kText.includes(word)) score += 15;
      if (qText.includes(word)) score += 10;
      if (tText.includes(word)) score += 8;
      if (aText.includes(word)) score += 3;
      // partial match
      for (const kw of qa.keywords) {
        const nkw = normalizeArabic(kw.toLowerCase());
        if (nkw.includes(word) || word.includes(nkw)) score += 6;
      }
    }

    // Exact phrase bonus
    if (normalizeArabic(q).includes(normalizeArabic(qa.question.toLowerCase()))) score += 50;
    return { qa, score };
  });

  return scores
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((s) => s.qa);
}

function normalizeArabic(text: string): string {
  return text
    .replace(/[أإآ]/g, "ا")
    .replace(/[ة]/g, "ه")
    .replace(/[ى]/g, "ي")
    .replace(/[\u064B-\u065F]/g, ""); // remove tashkeel
}

